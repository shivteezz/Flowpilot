package backend.controller;

import backend.model.AIAction;
import backend.service.GroqService;
import backend.service.N8nService;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.springframework.web.bind.annotation.*;

@RestController
@RequestMapping("/api/ai")
public class AIController {

    private final GroqService groqService;
    private final ObjectMapper objectMapper;
    private final N8nService n8nService;

    public AIController(
            GroqService groqService,
            N8nService n8nService
    ) {

        this.groqService = groqService;
        this.n8nService = n8nService;

        this.objectMapper =
                new ObjectMapper();
    }

    @PostMapping("/generate")
    public AIAction generate(
            @RequestBody AIRequest request
    ) {

        System.out.println(
                "================================="
        );

        System.out.println(
                "AI REQUEST RECEIVED"
        );

        System.out.println(
                "Prompt: "
                        + request.getPrompt()
        );

        System.out.println(
                "================================="
        );

        String response =
                groqService.understandAction(
                        request.getPrompt()
                );

        AIAction action;

        try {

            action =
                    objectMapper.readValue(
                            response,
                            AIAction.class
                    );

        } catch (Exception e) {

            throw new RuntimeException(
                    "AI returned invalid JSON: "
                            + response,
                    e
            );
        }

        System.out.println(
                "ACTION = "
                        + action.getAction()
        );

        /*
         * EMAIL AUTOMATION
         */

        if (
                "SEND_EMAIL".equals(
                        action.getAction()
                )
        ) {

            System.out.println(
                    "Executing email workflow..."
            );

            n8nService.sendEmail(
                    action.getRecipient(),
                    action.getSubject(),
                    action.getBody(),
                    action.getScheduledAt()
            );

            System.out.println(
                    "Email workflow triggered."
            );
        }

        /*
         * GENERAL AI
         *
         * Nothing else is required.
         * The answer generated by Groq
         * is already inside action.answer.
         */

        if (
                "GENERAL_QUERY".equals(
                        action.getAction()
                )
        ) {

            System.out.println(
                    "General AI response generated."
            );
        }

        return action;
    }

    public static class AIRequest {

        private String prompt;

        public String getPrompt() {
            return prompt;
        }

        public void setPrompt(
                String prompt
        ) {
            this.prompt = prompt;
        }
    }
}